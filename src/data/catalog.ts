export function calculateQualityScore(item: CatalogItem): number {
  return (item.pop * 0.42) + (item.smooth * 0.30) + (item.langs * 0.18) + ((2 - item.ads) * 10);
}

export function toSlug(str: string): string {
  return String(str || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

export function getItemHue(name: string): number {
  let h = 0;
  for (let i = 0; i < name.length; i++) {
    h = (h * 31 + name.charCodeAt(i)) % 360;
  }
  return h;
}

export function getItemInitials(name: string): string {
  return name.replace(/[^a-z0-9 ]/gi, "").split(/\s+/).map(x => x[0] || "").join("").slice(0, 2).toUpperCase();
}

export function getLogoCandidateList(item: CatalogItem): string[] {
  const slug = toSlug(item.name);
  const type = item.appType || "site";
  const domain = String(item.domain || "").toLowerCase();
  const domainKey = `${type}:${domain}`;
  const nameKey = `${type}:${slug}`;
  const localItem = STREAMCLOUD_ITEM_LOGOS[domainKey] || STREAMCLOUD_ITEM_LOGOS[nameKey];
  const local = MAHIFLIX_LOGOS[domain];
  const isWebsite = !item.appType;
  const keepFreekz = isWebsite && item.name.toLowerCase() === "freekz";

  const sources: string[] = [
    ...(item.logoSources || []),
    ...(!item.appType && localItem && !keepFreekz ? [localItem] : []),
    ...(local ? [local] : []),
    `https://${domain}/favicon.ico`,
    `https://${domain}/favicon.png`,
    `https://${domain}/favicon.svg`,
    `https://www.google.com/s2/favicons?sz=256&domain=${encodeURIComponent(domain)}`,
    `https://icons.duckduckgo.com/ip3/${encodeURIComponent(domain)}.ico`
  ];

  return Array.from(new Set(sources.filter(Boolean)));
}
